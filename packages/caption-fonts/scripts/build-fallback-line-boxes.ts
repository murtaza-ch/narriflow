/**
 * Rebuilds src/fallback-line-boxes-data.ts from the pinned fallback faces and the Studio's
 * @font-face rules: `bun packages/caption-fonts/scripts/build-fallback-line-boxes.ts`.
 *
 * Per face: the Win line box libass anchors a word by (`fontFileMetricsEm`), the unicode-range the
 * browser walks to pick the face (apps/web/app/caption-script-fonts.css), and the spaces,
 * punctuation and digits its cmap draws (a neutral cluster stays in the face before it when that
 * face has it, as in the worker's planner). fallback-line-boxes.test.ts fails when the table and
 * the fonts or the CSS disagree.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { create } from "fontkit";
import { CAPTION_FALLBACK_FONTS, captionFallbackFontPath, fontFileMetricsEm } from "../src/fallback-fonts";

const css = readFileSync(new URL("../../../apps/web/app/caption-script-fonts.css", import.meta.url), "utf8");
const cssRanges = new Map<string, string>();
for (const match of css.matchAll(/@font-face\s*\{([\s\S]*?)\}/g)) {
  const file = /([^/"]+)"\) format/.exec(match[1]!)?.[1];
  const ranges = /unicode-range:\s*([^;]+);/.exec(match[1]!)?.[1];
  if (file && ranges) cssRanges.set(file, ranges);
}

const NEUTRAL = /^[\p{Z}\p{P}\p{N}]$/u;

function parseRanges(value: string): [number, number][] {
  return value.split(",").map((part) => {
    const [from, to = from] = part.trim().replace(/^U\+/, "").split("-");
    return [Number.parseInt(from!, 16), Number.parseInt(to!, 16)];
  });
}

function compress(codePoints: readonly number[]): [number, number][] {
  const ranges: [number, number][] = [];
  for (const codePoint of codePoints) {
    const last = ranges[ranges.length - 1];
    if (last && last[1] === codePoint - 1) last[1] = codePoint;
    else ranges.push([codePoint, codePoint]);
  }
  return ranges;
}

const hex = (ranges: readonly (readonly [number, number])[]) => ranges.map(([from, to]) => `[0x${from.toString(16)}, 0x${to.toString(16)}]`).join(", ");

const entries = CAPTION_FALLBACK_FONTS.map((font) => {
  const path = captionFallbackFontPath(font);
  const { ascentEm, descentEm } = fontFileMetricsEm(path);
  const ranges = cssRanges.get(font.file);
  if (!ranges) throw new Error(`${font.file}: no @font-face rule in caption-script-fonts.css`);
  const face = create(readFileSync(path)) as unknown as { characterSet: number[] };
  const neutral = compress(face.characterSet.filter((codePoint) => NEUTRAL.test(String.fromCodePoint(codePoint))).sort((left, right) => left - right));
  return [
    `  {`,
    `    file: ${JSON.stringify(font.file)},`,
    `    role: ${JSON.stringify(font.role)},`,
    ...("languages" in font ? [`    languages: ${JSON.stringify(font.languages)},`] : []),
    `    ascentEm: ${ascentEm},`,
    `    descentEm: ${descentEm},`,
    `    ranges: [${hex(parseRanges(ranges))}],`,
    `    neutral: [${hex(neutral)}],`,
    `  },`,
  ].join("\n");
});
writeFileSync(
  new URL("../src/fallback-line-boxes-data.ts", import.meta.url),
  `// Generated by scripts/build-fallback-line-boxes.ts from the pinned fallback faces. Do not edit.\n` +
    `// biome-ignore-all lint/suspicious/noApproximativeNumericConstant: a font's descent that happens to be 0.707\n` +
    `import type { CaptionFallbackLineBox } from "./fallback-line-boxes";\n\n` +
    `/** The fallback chain in lookup order (\`CAPTION_FALLBACK_FONTS\`), with what the browser needs to anchor a word by the face that draws it. */\n` +
    `export const CAPTION_FALLBACK_LINE_BOXES: readonly CaptionFallbackLineBox[] = [\n${entries.join("\n")}\n];\n`,
);
console.log(`${entries.length} faces`);
