/**
 * Rebuilds src/glyph-coverage-data.ts from the pinned fallback faces:
 * `bun packages/caption-fonts/scripts/build-glyph-coverage.ts`.
 *
 * The table is the union of the code points the fallback chain draws, as
 * inclusive [from, to] ranges, so the browser can ask the same question the
 * export planner answers with fontkit. glyph-coverage.test.ts fails when the
 * table and the fonts disagree.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { create } from "fontkit";
import { CAPTION_FALLBACK_FONTS, captionFallbackFontPath } from "../src/fallback-fonts";

const covered = new Set<number>();
for (const font of CAPTION_FALLBACK_FONTS) {
  const face = create(readFileSync(captionFallbackFontPath(font))) as unknown as { characterSet: number[] };
  for (const codePoint of face.characterSet) covered.add(codePoint);
}
const sorted = [...covered].sort((left, right) => left - right);
const flat: number[] = [];
for (const codePoint of sorted) {
  if (flat.length > 0 && flat[flat.length - 1] === codePoint - 1) flat[flat.length - 1] = codePoint;
  else flat.push(codePoint, codePoint);
}
const body = flat.reduce<string[]>((lines, value, index) => {
  if (index % 2 === 0) lines.push(`  [0x${value.toString(16)}, 0x${flat[index + 1]!.toString(16)}],`);
  return lines;
}, []);
writeFileSync(
  new URL("../src/glyph-coverage-data.ts", import.meta.url),
  `// Generated by scripts/build-glyph-coverage.ts from the pinned fallback faces. Do not edit.\n` +
    `/** Inclusive code point ranges at least one pinned fallback face draws. */\n` +
    `export const CAPTION_COVERED_RANGES: readonly (readonly [number, number])[] = [\n${body.join("\n")}\n];\n`,
);
console.log(`${sorted.length} code points in ${body.length} ranges`);
