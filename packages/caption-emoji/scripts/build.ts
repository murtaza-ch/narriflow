/**
 * Compiles `source/` into `src/generated/`: the index (`index-data.ts`), one or more art shards
 * per group (`art/<group>-<n>.ts`) and the shard loader table (`shards.ts`).
 *
 *   bun run --cwd packages/caption-emoji build
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { encodeShardEntry, type ShardEntry } from "../src/encoding";
import { CAPTION_EMOJI_BOX } from "../src/geometry";
import { parseCaptionEmojiPath } from "../src/path";
import { captionEmojiShardKey } from "../src/shard-key";
import { type CompiledDesign, compileDesign, loadCanvasKit } from "./compile";
import { readCatalog } from "./catalog";

const root = fileURLToPath(new URL("..", import.meta.url));
const sourceDir = join(root, "source");
const outDir = join(root, "src", "generated");
/** A shard's target size; a group over it is split by id hash. */
const SHARD_BYTES = 350_000;

const catalog = readCatalog(sourceDir);
const ck = await loadCanvasKit();

const compiled = new Map<string, CompiledDesign>();
const failures: string[] = [];
const warnings: string[] = [];
let index = 0;
for (const design of catalog.designs) {
  index += 1;
  try {
    const source = readFileSync(join(sourceDir, design.file), "utf8");
    const result = compileDesign(ck, source, { hasTones: design.hasTones });
    compiled.set(design.id, result);
    for (const warning of result.warnings) warnings.push(`${design.id}: ${warning}`);
  } catch (error) {
    failures.push(`${design.id}: ${(error as Error).message}`);
  }
  if (index % 200 === 0) console.error(`compiled ${index}/${catalog.designs.length}`);
}

// Index.
const indexRows = catalog.designs.map((d) => [d.id, d.name, d.glyph, d.group, d.keywords.join(" "), (d.hasTones ? 1 : 0) | (d.kind === "phrase" ? 2 : 0)]);
const groups = catalog.groups.map((g) => [g.id, g.name]);

// Shards: entries grouped by group, in catalog order; a large group splits by id hash.
const byGroup = new Map<string, [string, ShardEntry][]>();
for (const design of catalog.designs) {
  const art = compiled.get(design.id);
  if (!art) continue;
  const rows = byGroup.get(design.group) ?? [];
  rows.push([design.id, encodeShardEntry({ layers: art.layers, outline: art.outline })]);
  byGroup.set(design.group, rows);
}
const shardCounts: Record<string, number> = {};
const shards = new Map<string, Record<string, ShardEntry>>();
for (const group of catalog.groups) {
  const rows = byGroup.get(group.id) ?? [];
  const bytes = JSON.stringify(rows).length;
  const count = Math.max(1, Math.ceil(bytes / SHARD_BYTES));
  shardCounts[group.id] = count;
  for (let n = 0; n < count; n += 1) shards.set(`${group.id}-${n}`, {});
  for (const [id, entry] of rows) shards.get(captionEmojiShardKey(id, group.id, count))![id] = entry;
}

const header = "// Generated by scripts/build.ts from source/. Do not edit.\n";
rmSync(outDir, { recursive: true, force: true });
mkdirSync(join(outDir, "art"), { recursive: true });
writeFileSync(
  join(outDir, "index-data.ts"),
  `${header}export const INDEX_JSON = ${JSON.stringify(JSON.stringify({ groups, rows: indexRows }))};\n`,
);
const loaders: string[] = [];
for (const [key, entries] of shards) {
  writeFileSync(join(outDir, "art", `${key}.ts`), `${header}export default ${JSON.stringify(JSON.stringify(entries))};\n`);
  loaders.push(`  ${JSON.stringify(key)}: () => import("./art/${key}"),`);
}
writeFileSync(
  join(outDir, "shards.ts"),
  `${header}export const SHARD_COUNTS: Readonly<Record<string, number>> = ${JSON.stringify(shardCounts)};\n\n` +
    `export const SHARD_LOADERS: Readonly<Record<string, () => Promise<{ default: string }>>> = {\n${loaders.join("\n")}\n};\n`,
);

// Report.
const layerCounts = [...compiled.values()].map((c) => c.layers.length).sort((a, b) => a - b);
const sizes = readdirSync(join(outDir, "art")).map((f) => [f, readFileSync(join(outDir, "art", f)).length] as const);
const artBytes = sizes.reduce((sum, [, n]) => sum + n, 0);
const indexBytes = readFileSync(join(outDir, "index-data.ts")).length;
const layerHistogram: Record<number, number> = {};
for (const n of layerCounts) layerHistogram[n] = (layerHistogram[n] ?? 0) + 1;
// Every point (control points too: libass sizes a drawing by them) against the drawing box.
const reach = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
const outsideBox: string[] = [];
const box = CAPTION_EMOJI_BOX;
for (const [id, art] of compiled) {
  for (const d of [art.outline, ...art.layers.map((layer) => layer.d)]) {
    for (const command of parseCaptionEmojiPath(d)) {
      for (let i = 1; i < command.length; i += 2) {
        const [x, y] = [command[i] as number, command[i + 1] as number];
        reach.minX = Math.min(reach.minX, x);
        reach.minY = Math.min(reach.minY, y);
        reach.maxX = Math.max(reach.maxX, x);
        reach.maxY = Math.max(reach.maxY, y);
        if (x < box.x || y < box.y || x > box.x + box.width || y > box.y + box.height) outsideBox.push(id);
      }
    }
  }
}
console.log(
  JSON.stringify(
    {
      designs: catalog.designs.length,
      compiled: compiled.size,
      failures,
      warnings: warnings.length,
      warningSamples: warnings.slice(0, 20),
      layers: { min: layerCounts[0], median: layerCounts[Math.floor(layerCounts.length / 2)], max: layerCounts[layerCounts.length - 1] },
      layerHistogram,
      reach,
      outsideBox: [...new Set(outsideBox)],
      sourceLayers: [...compiled.values()].reduce((sum, c) => sum + c.sourceLayers, 0),
      hiddenLayers: [...compiled.values()].reduce((sum, c) => sum + c.hiddenLayers, 0),
      designsWithHiddenLayers: [...compiled].filter(([, c]) => c.hiddenLayers > 0).map(([id, c]) => `${id} ${c.hiddenLayers}`),
      outputLayers: layerCounts.reduce((sum, n) => sum + n, 0),
      indexBytes,
      artBytes,
      shards: Object.fromEntries(sizes),
    },
    null,
    2,
  ),
);
if (failures.length > 0 || outsideBox.length > 0) process.exit(1);
