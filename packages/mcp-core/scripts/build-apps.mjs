import { build, write } from "bun";
import { fileURLToPath } from "node:url";

// The web app's official marks, so one source serves every surface. Inlined SVGs
// share a document, so each mark gets its own ids and loses its global classes.
const social = fileURLToPath(new URL("../../../apps/web/public/images/social/", import.meta.url));
const marks = { tiktok: "tiktok-dark", youtube: "youtube", instagram: "instagram", facebook: "facebook", linkedin: "linkedin", x: "x-dark" };
function inlineMark(name, svg) {
  const classes = Object.fromEntries([...svg.matchAll(/\.(cls-\d+)\{([^}]*)\}/g)].map((match) => [match[1], match[2]]));
  return svg.replace(/<title>.*?<\/title>/s, "").replace(/<style>.*?<\/style>/s, "").replace(/<defs>\s*<\/defs>/, "")
    .replace(/class="(cls-\d+)"/g, (_, name_) => `style="${classes[name_]}"`)
    .replace(/\s(?:width|height)="\d+"(?=[^>]*viewBox)/g, "")
    .replace(/\bid="([^"]+)"/g, `id="${name}-$1"`).replace(/href="#/g, `href="#${name}-`).replace(/url\(#/g, `url(#${name}-`)
    .replace(/#fff\b/gi, name === "tiktok" || name === "x" ? "currentColor" : "#fff")
    .replace(/^<svg /, '<svg class="logo" aria-hidden="true" ');
}
const entries = await Promise.all(Object.entries(marks).map(async ([name, file]) => [name, inlineMark(name, await Bun.file(`${social}${file}.svg`).text())]));
await write(fileURLToPath(new URL("../src/mcp-apps/v2/platform-logos.ts", import.meta.url)),
  `// Generated by scripts/build-apps.mjs from apps/web/public/images/social. Do not edit.\nexport const platformLogos: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`);

const source = fileURLToPath(new URL("../src/mcp-apps/v2/app.ts", import.meta.url));
const target = fileURLToPath(new URL("../src/mcp-apps/v2/app-script.ts", import.meta.url));
const result = await build({ entrypoints: [source], target: "browser", minify: true });
if (!result.success || result.outputs.length !== 1) throw new Error("MCP App bundle compilation failed", { cause: result.logs });
await write(target, `// Generated by scripts/build-apps.mjs. Edit app.ts, then run build:apps.\nexport const narriflowAppScript: string = ${JSON.stringify(await result.outputs[0].text())};\n`);
